// Helper to calculate initial batch cost using exact formula: (TP + VAT) - Discount
function createSeedBatch(
  batchId: string,
  medicineId: string,
  batchNum: string,
  expiry: string,
  tp: number,
  vatPercent: number,
  discountPercent: number,
  sellingPrice: number,
  stock: number,
  supplierId: string,
  group?: string
): Batch {
  const calc = calculateCostPrice(tp, vatPercent, discountPercent);
  return {
    BatchID: batchId,
    MedicineID: medicineId,
    BatchNumber: batchNum,
    ExpiryDate: expiry,
    PurchasePrice: tp,
    TradePrice: tp,
    TradePriceVat: vatPercent,
    CostPrice: calc.costPrice,
    SellingPrice: sellingPrice,
    CurrentStock: stock,
    SupplierID: supplierId,
    Group: group,
  };
}

